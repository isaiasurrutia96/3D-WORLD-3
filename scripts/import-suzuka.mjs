import {readFileSync,writeFileSync} from 'node:fs';

// Import the same published route used in the map shown to the player.
// Re-running this script needs no network connection or extra packages.
const source=readFileSync(new URL('../docs/references/suzuka.svg',import.meta.url),'utf8');
const points=source.match(/<polyline points="([^"]+)"/)[1].trim().split(/\s+/).map(pair=>pair.split(',').map(Number));
const distances=[0];for(let i=1;i<points.length;i++)distances.push(distances.at(-1)+Math.hypot(points[i][0]-points[i-1][0],points[i][1]-points[i-1][1]));
const length=distances.at(-1)+Math.hypot(points[0][0]-points.at(-1)[0],points[0][1]-points.at(-1)[1]);
function simplify(first,last,tolerance=.3){
 const a=points[first],b=points[last],dx=b[0]-a[0],dz=b[1]-a[1],length2=dx*dx+dz*dz;let best=tolerance,index=-1;
 for(let i=first+1;i<last;i++){const p=points[i],t=Math.max(0,Math.min(1,((p[0]-a[0])*dx+(p[1]-a[1])*dz)/(length2||1))),distance=Math.hypot(p[0]-a[0]-dx*t,p[1]-a[1]-dz*t);if(distance>best){best=distance;index=i;}}
 return index<0?[first,last]:[...simplify(first,index,tolerance).slice(0,-1),...simplify(index,last,tolerance)];
}
const ease=t=>{t=Math.max(0,Math.min(1,t));return t*t*(3-2*t);};
const height=t=>12*ease((t-.76)/.06)*ease((.94-t)/.05);
const indices=simplify(0,points.length-1);
const entry=points.reduce((best,p)=>p[1]>best[1]?p:best);
const layout={source:'https://github.com/LigasAVBrasil/RaceTracksAPI/blob/e9ec550b1d641f8183d0ee9223bd15abed3fbdfa/images/track_8.1.svg',sourceLength:length,entry,points:indices.map(i=>[...points[i],Number(height(distances[i]/length).toFixed(5))])};
writeFileSync(new URL('../src/data/suzuka-layout.js',import.meta.url),`// Generated by scripts/import-suzuka.mjs from docs/references/suzuka.svg.\nexport const SUZUKA_LAYOUT=${JSON.stringify(layout)};\n`);
console.log(`Imported ${points.length} source points as ${indices.length} control points.`);
